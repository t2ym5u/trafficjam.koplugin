#!/bin/bash
# Rebuilds levels_data.lua: 8 seeds in parallel, then a merge. Deterministic.
# Takes about 5 min on an 8-core desktop. Run from anywhere.
set -e
here="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
for seed in 1 2 3 4 5 6 7 8; do
    luajit "$here/gen_levels.lua" 90 "$seed" > "$tmp/part$seed.txt" 2> "$tmp/log$seed.txt" &
done
wait
out="$here/../levels_data.lua"
{
    echo "-- Level bank, generated by tools/build_levels.sh -- do not edit by hand."
    echo "-- One band header per difficulty, then one line per level: 36-character"
    echo "-- board (row by row, \".\" empty, \"A\" the black car) and its optimal moves."
    echo "-- Kept as a .lua file so PluginManager ships it (it fetches .lua files only)."
    echo "return [["
    luajit "$here/merge_levels.lua" "$tmp"/part*.txt
    echo "]]"
} > "$out"
rm -rf "$tmp"
